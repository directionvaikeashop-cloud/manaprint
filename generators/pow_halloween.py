CARD_H = CARD_W / ASPECT
_BLOC_H = ROWS_PAGE * CARD_H + (ROWS_PAGE - 1) * GUTTER_Y
MARGE_TOP = 7 * mm
MARGE_BOT = PAGE_H - MARGE_TOP - _BLOC_H

