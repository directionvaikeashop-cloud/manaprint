# ── GEOMETRIE DE LA FEUILLE (A4 PAYSAGE, 4 colonnes x 4 rangees) ──
PAGE_W, PAGE_H = landscape(A4)
ASPECT = 377.0 / 243.0            # largeur/hauteur d'un carton (releve sur la maquette)
COLS_PAGE = 4
ROWS_PAGE = 4
