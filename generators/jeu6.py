def _graver_planche(c):
    nom = "JEU6_DECOR"
    if not getattr(c, "_jeu6_forme_faite", False):
        c.beginForm(nom, lowerx=0, lowery=0, upperx=FEUILLE_W, uppery=FEUILLE_H)
        p = c.beginPath()
        for contour in _DECOR.split("|"):
            i = 0
            n = len(contour)
            while i < n:
                cmd = contour[i]
                j = i + 1
                while j < n and contour[j] not in "mlc":
                    j += 1
                v = [float(x) for x in contour[i + 1:j].split(",")]
                if cmd == "m":
                    p.moveTo(v[0] / 1000.0 * FEUILLE_W, FEUILLE_H - v[1] / 1000.0 * FEUILLE_H)
                elif cmd == "l":
                    p.lineTo(v[0] / 1000.0 * FEUILLE_W, FEUILLE_H - v[1] / 1000.0 * FEUILLE_H)
                else:
                    p.curveTo(v[0] / 1000.0 * FEUILLE_W, FEUILLE_H - v[1] / 1000.0 * FEUILLE_H,
                              v[2] / 1000.0 * FEUILLE_W, FEUILLE_H - v[3] / 1000.0 * FEUILLE_H,
                              v[4] / 1000.0 * FEUILLE_W, FEUILLE_H - v[5] / 1000.0 * FEUILLE_H)
                i = j
            p.close()
        c.drawPath(p, stroke=0, fill=1)
        c.endForm()
        c._jeu6_forme_faite = True
    return nom


def _poser_decor(c, x0, y0, couleurs):
    nom = _graver_planche(c)
    marge = 0.3 * mm
    for gi, (bord, cadre, _pts, _se) in enumerate(CARTES):
        gx = x0 + bord[0] / 1000.0 * FEUILLE_W - marge
        gl = (bord[1] - bord[0]) / 1000.0 * FEUILLE_W + 2 * marge
        gy = y0 + FEUILLE_H - cadre[1] / 1000.0 * FEUILLE_H - marge
        gh = (cadre[1] - cadre[0]) / 1000.0 * FEUILLE_H + 2 * marge
        c.saveState()
        fen = c.beginPath()
        fen.rect(gx, gy, gl, gh)
        c.clipPath(fen, stroke=0, fill=0)
        c.setFillColor(couleurs[gi])
        c.translate(x0, y0)
        c.doForm(nom)
        c.restoreState()


def _gen_grille(rng):
    """SIX numeros, un par colonne : B 1-15, I 16-30, N 31-45, G 46-60,
    O 61-75, et 76-90 (de gauche a droite)."""
    return [rng.randint(lo, hi) for lo, hi in PLAGES]


def _tirer(rng, deja):
    for _ in range(600):
        g = _gen_grille(rng)
        cle = tuple(g)
        if cle not in deja:
            deja.add(cle)
            return g
    return g


def _dessiner_feuille(c, x0, y0, grilles, series, couleurs, titre_jeu="",
                      telephone="", style="eco"):
    police_ch, gris_ch = _style_chiffres(style)
    _poser_decor(c, x0, y0, couleurs)
    taille = _T_CASE

    def MX(v):
        return x0 + v / 1000.0 * FEUILLE_W

    def MY(v):
        return y0 + FEUILLE_H - v / 1000.0 * FEUILLE_H

    for gi, (bord, cadre, pts, se) in enumerate(CARTES):
        grille = grilles[gi]
        for k in range(6):
            val = grille[k]
            cx = MX(pts[k][0]); cy = MY(pts[k][1]) - taille * 0.36
            if _sec:
                _sec.chiffre_micro(c, val, cx, cy, taille, gris_ch, police_ch,
                                   epaisseur=_GRAS_TRAIT)
            else:
                c.setFillColor(gris_ch)
                c.setFont(police_ch, taille)
                c.drawCentredString(cx, cy, str(val))
        c.setFillColor(GRIS)
        c.setFont(POLICE, _T_SERIE)
        c.drawString(MX(se[0]), MY(se[1]), "%06d" % series[gi])
        if _sec:
            try:
                _sec.cadre_micro(c, MX(bord[0]), MY(cadre[1]),
                                 MX(bord[1]) - MX(bord[0]),
                                 MY(cadre[0]) - MY(cadre[1]),
                                 series[gi], retrait=0.6 * mm)
            except Exception:
                pass


def generer_pdf(nb_cartes=20, serie_start=1, theme="", couleur=True,
                nom_evenement="", titre_jeu="", couleur_perso="", date_lieu="",
                telephone="", style="eco", evenement_id="", motif="",
                page_start=1, **_):
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=landscape(A4), pageCompression=1)
    nb_cartes = max(1, min(int(nb_cartes), 20000))
    nb_pages = (nb_cartes + CARTES_PAGE - 1) // CARTES_PAGE
    rng = random.Random(600060 + int(serie_start))
    serie = int(serie_start)
    no_page = max(1, int(page_start))
    _deja = set()
    for _p in range(nb_pages):
        if nom_evenement:
            c.setFillColor(colors.black); c.setFont(POLICE, 8)
            c.drawCentredString(PAGE_W / 2, PAGE_H - 4.6 * mm, nom_evenement)
        c.setFillColor(GRIS_CLAIR); c.setFont(POLICE, 5.5)
        c.drawRightString(PAGE_W - 5 * mm, PAGE_H - 4.6 * mm, "%03d" % no_page)
        grilles = [_tirer(rng, _deja) for _k in range(CARTES_PAGE)]
        series = [serie + k for k in range(CARTES_PAGE)]
        couleurs = [colors.HexColor(
            couleur_perso if (couleur and couleur_perso)
            else RAINBOW[(s - 1) % len(RAINBOW)] if couleur else TRAIT_NB)
            for s in series]
        _dessiner_feuille(c, MARGE_X, MARGE_Y, grilles, series, couleurs,
                          titre_jeu, telephone, style=style)
        serie += CARTES_PAGE
        c.showPage()
        no_page += 1
    c.save()
    buf.seek(0)
    return buf


